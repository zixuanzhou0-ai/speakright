function parseArgs(values) {
  const command = values[0];
  const args = new Set(values.slice(1));
  const valueFor = (prefix, fallback) =>
    values
      .find((value) => value.startsWith(`${prefix}=`))
      ?.slice(prefix.length + 1) ?? fallback;
  return { command, args, valueFor };
}

function writeJson(filePath, value) {
  mkdirSync(path.dirname(filePath), { recursive: true });
  const temporary = `${filePath}.tmp`;
  writeFileSync(
    temporary,
    `${JSON.stringify(redactSecrets(value), null, 2)}\n`,
    "utf8",
  );
  rmSync(filePath, { force: true });
  renameSync(temporary, filePath);
}

function writeJsonl(filePath, values) {
  mkdirSync(path.dirname(filePath), { recursive: true });
  const temporary = `${filePath}.tmp`;
  const content = values
    .map((value) => JSON.stringify(redactSecrets(value)))
    .join("\n");
  writeFileSync(temporary, content ? `${content}\n` : "", "utf8");
  rmSync(filePath, { force: true });
  renameSync(temporary, filePath);
}

function appendJsonl(filePath, value) {
  mkdirSync(path.dirname(filePath), { recursive: true });
  appendFileSync(filePath, `${JSON.stringify(redactSecrets(value))}\n`, "utf8");
}

function readJson(filePath) {
  return JSON.parse(readFileSync(filePath, "utf8"));
}

function readJsonl(filePath) {
  if (!existsSync(filePath)) return [];
  const result = [];
  for (const line of readFileSync(filePath, "utf8").split(/\r?\n/u)) {
    if (!line.trim()) continue;
    try {
      result.push(JSON.parse(line));
    } catch {
      // An interrupted final checkpoint is ignored and regenerated by SHA.
    }
  }
  return result;
}

function requireFile(filePath, instruction) {
  if (!existsSync(filePath)) throw new Error(instruction);
  return readJson(filePath);
}

