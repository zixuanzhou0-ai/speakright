async function convertToAzureWav(asset) {
  const reusable = path.join(
    legacyOutputRoot,
    "wav-cache",
    `${asset.sha256}.wav`,
  );
  if (existsSync(reusable)) return reusable;
  const wavPath = path.join(outputRoot, "wav-cache", `${asset.sha256}.wav`);
  if (existsSync(wavPath)) return wavPath;
  mkdirSync(path.dirname(wavPath), { recursive: true });
  await execFileAsync(
    "ffmpeg",
    [
      "-y",
      "-loglevel",
      "error",
      "-i",
      path.resolve(root, asset.desktopPath),
      "-ac",
      "1",
      "-ar",
      "16000",
      "-sample_fmt",
      "s16",
      wavPath,
    ],
    { windowsHide: true, timeout: 30_000 },
  );
  return wavPath;
}

async function withRetry(worker) {
  for (let attempt = 0; attempt < 4; attempt += 1) {
    try {
      return await worker();
    } catch (error) {
      const retryable =
        error?.status === 429 ||
        (typeof error?.status === "number" && error.status >= 500) ||
        /fetch|network|timeout|abort/i.test(String(error?.message ?? error));
      if (!retryable || attempt === 3) throw error;
      await new Promise((resolve) => setTimeout(resolve, 1000 * 2 ** attempt));
    }
  }
  throw new Error("Retry loop exhausted");
}

async function runPool(items, concurrency, worker) {
  let cursor = 0;
  await Promise.all(
    Array.from({ length: concurrency }, async () => {
      while (cursor < items.length) {
        const index = cursor++;
        await worker(items[index], index);
      }
    }),
  );
}

function chooseSmokeAssets(inventory) {
  const whispers = new Map(
    readJsonl(whisperBlindPath).map((row) => [row.assetId, row]),
  );
  return LANGUAGE_IDS.flatMap((languageId) => {
    const candidates = inventory.assets.filter(
      (asset) =>
        asset.languageId === languageId && isWordBearingAuditAsset(asset),
    );
    const clear = candidates.find(
      (asset) => whispers.get(asset.assetId)?.outcome === "exact",
    );
    const shortest = [...candidates].sort(
      (a, b) => a.durationSeconds - b.durationSeconds,
    )[0];
    const risk =
      candidates.find((asset) =>
        ["different-word", "accepted-homophone", "uncertain"].includes(
          whispers.get(asset.assetId)?.outcome,
        ),
      ) ?? candidates[Math.floor(candidates.length / 2)];
    const selected = new Map();
    for (const item of [clear, shortest, risk, ...candidates]) {
      if (item) selected.set(item.assetId, item);
      if (selected.size === 3) break;
    }
    if (selected.size !== 3) {
      throw new Error(
        `Gemini/Azure smoke requires 3 assets for ${languageId}.`,
      );
    }
    return [...selected.values()];
  });
}

async function azureSttRunCommand(parsed) {
  const rotatedKeyConfirmed = parsed.args.has("--rotated-key-confirmed");
  const exposedKeyAuthorizedOnce = parsed.args.has("--use-exposed-key-once");
  if (
    !parsed.args.has("--confirm") ||
    (!rotatedKeyConfirmed && !exposedKeyAuthorizedOnce)
  ) {
    throw new Error(
      "Azure blind STT requires --confirm plus either --rotated-key-confirmed or the explicit one-batch override --use-exposed-key-once.",
    );
  }
  const credentialRiskMode = rotatedKeyConfirmed
    ? "rotated-key"
    : "exposed-key-authorized-for-one-batch";
  const mode = parsed.valueFor("--mode", "smoke");
  if (!new Set(["smoke", "full"]).has(mode))
    throw new Error(`Invalid mode: ${mode}`);
  const inventory = requireInventory();
  if (mode === "full") {
    const summaryPath = path.join(blindRoot, "azure-stt-smoke-summary.json");
    if (!existsSync(summaryPath) || readJson(summaryPath).passed !== true) {
      throw new Error(
        "A passing Azure blind STT smoke is required before full mode.",
      );
    }
  }
  const { value: azure, source } = await readSpeakRightCredential("azure");
  if (
    !azure?.subscriptionKey ||
    azure.region?.toLowerCase() !== fixedAzureRegion
  ) {
    throw new Error(`Azure credential must use ${fixedAzureRegion}.`);
  }
  const cmu = loadCmuDictReference();
  const homophoneGroups = loadHomophoneGroups();
  const existing = new Map(
    readJsonl(azureBlindPath).map((row) => [row.sha256, row]),
  );
  const candidates = inventory.assets.filter(isWordBearingAuditAsset);
  const selected = mode === "smoke" ? chooseSmokeAssets(inventory) : candidates;
  const items = selected.filter((asset) => !existing.has(asset.sha256));
  const failures = [];
  await runPool(items, 2, async (asset, index) => {
    try {
      const result = await withRetry(() =>
        convertToAzureWav(asset).then((wavPath) =>
          recognizeAzureWordBlind({
            subscriptionKey: azure.subscriptionKey,
            region: fixedAzureRegion,
            languageId: asset.languageId,
            wavPath,
          }),
        ),
      );
      if (!result.ok) {
        throw new Error(
          `Blind STT request failed (${result.recognitionStatus})`,
        );
      }
      const recognizedText = result.recognizedText ?? "";
      appendJsonl(azureBlindPath, {
        version: 1,
        assetId: asset.assetId,
        sha256: asset.sha256,
        listener: "azure-stt",
        heardText: recognizedText,
        detectedLanguage: asset.languageId,
        confidence: result.confidence,
        modelRevision: "azure-standard-stt-2026-07-14",
        promptPolicyVersion: "no-reference-text-v1",
        referenceTextSent: false,
        credentialSource: source,
        credentialRiskMode,
        createdAt: new Date().toISOString(),
        outcome: classifyBlindTranscript({
          expected: asset.text,
          actual: recognizedText,
          languageId: asset.languageId,
          homophoneGroups,
          cmuReference: cmu,
        }),
      });
      console.log(
        `Azure blind ${mode} ${index + 1}/${items.length}: ${asset.assetId}`,
      );
    } catch (error) {
      failures.push({
        assetId: asset.assetId,
        error: String(error?.message ?? error),
      });
    }
  });
  const observations = readJsonl(azureBlindPath);
  const selectedObservations = selected
    .map((asset) => observations.find((row) => row.sha256 === asset.sha256))
    .filter(Boolean);
  const stableCount = selectedObservations.filter((row) =>
    ["exact", "accepted-homophone", "orthographic-variant"].includes(
      row.outcome,
    ),
  ).length;
  const noSpeechCount = selectedObservations.filter(
    (row) => row.outcome === "no-speech",
  ).length;
  const passed =
    failures.length === 0 && selectedObservations.length === selected.length;
  const summary = {
    mode,
    generatedAt: new Date().toISOString(),
    requested: selected.length,
    attempted: items.length,
    stableCount,
    noSpeechCount,
    credentialRiskMode,
    failed: failures.length,
    failures,
    passed,
    warning:
      mode === "smoke" && stableCount < Math.ceil(selected.length * 0.75)
        ? "Azure ordinary STT is operational but unreliable on this isolated-word smoke set; use it only as one noisy signal."
        : null,
  };
  writeJson(path.join(blindRoot, `azure-stt-${mode}-summary.json`), summary);
  if (!passed) process.exitCode = 1;
}

function mimeTypeForAudio(filePath) {
  const extension = path.extname(filePath).toLowerCase();
  return (
    {
      ".mp3": "audio/mpeg",
      ".m4a": "audio/mp4",
      ".wav": "audio/wav",
      ".ogg": "audio/ogg",
    }[extension] ?? "application/octet-stream"
  );
}

function readProxyApiKey(filePath) {
  const entries = readJson(filePath);
  const active = Array.isArray(entries)
    ? entries.find((entry) => entry.active !== false && entry.key)
    : null;
  if (!active?.key)
    throw new Error("No active Gemini proxy API key was found.");
  return active.key;
}

function parseGeminiJson(content) {
  const cleaned = String(content ?? "")
    .trim()
    .replace(/^```(?:json)?\s*/iu, "")
    .replace(/\s*```$/u, "");
  return JSON.parse(cleaned);
}

async function askGeminiBlind({ asset, baseUrl, apiKey, model }) {
  const endpoint = new URL("/v1/chat/completions", baseUrl);
  const filePath = path.resolve(root, asset.desktopPath);
  const audio = readFileSync(filePath).toString("base64");
  const response = await fetch(endpoint, {
    method: "POST",
    headers: {
      Authorization: `Bearer ${apiKey}`,
      "Content-Type": "application/json",
    },
    body: JSON.stringify(
      buildGeminiBlindRequest({
        languageId: asset.languageId,
        model,
        mimeType: mimeTypeForAudio(filePath),
        audioBase64: audio,
      }),
    ),
    signal: AbortSignal.timeout(90_000),
  });
  if (!response.ok) {
    const error = new Error(`Gemini proxy failed (${response.status}).`);
    error.status = response.status;
    throw error;
  }
  const payload = await response.json();
  return parseGeminiJson(payload?.choices?.[0]?.message?.content);
}

async function geminiRunCommand(parsed, forcedMode) {
  if (!parsed.args.has("--confirm")) {
    throw new Error(
      "Gemini blind listening requires --confirm after reviewing the blind plan.",
    );
  }
  const mode = forcedMode ?? parsed.valueFor("--mode", "smoke");
  const baseUrl = assertLoopbackUrl(
    parsed.valueFor("--base-url", "http://127.0.0.1:8888"),
  );
  const apiKeyFile = path.resolve(
    parsed.valueFor("--api-key-file", "E:\\Gemini-Cli-Proxy\\api_keys.json"),
  );
  const apiKey = readProxyApiKey(apiKeyFile);
  const model = parsed.valueFor("--model", "gemini-3.1-pro-preview");
  if (mode === "full") {
    const smokePath = path.join(blindRoot, "gemini-smoke-summary.json");
    if (!existsSync(smokePath) || readJson(smokePath).passed !== true) {
      throw new Error(
        "A passing 12-item Gemini smoke is required before full mode.",
      );
    }
  }
  const inventory = requireInventory();
  const cmu = loadCmuDictReference();
  const homophoneGroups = loadHomophoneGroups();
  const existing = new Map(
    readJsonl(geminiBlindPath).map((row) => [row.sha256, row]),
  );
  const candidates = inventory.assets.filter(isWordBearingAuditAsset);
  const selected = mode === "smoke" ? chooseSmokeAssets(inventory) : candidates;
  const items = selected.filter((asset) => !existing.has(asset.sha256));
  const failures = [];
  for (const [index, asset] of items.entries()) {
    try {
      const heard = await withRetry(() =>
        askGeminiBlind({ asset, baseUrl, apiKey, model }),
      );
      const heardText = String(heard.heardText ?? "").trim();
      if (!heardText) throw new Error("Gemini returned no heardText.");
      appendJsonl(geminiBlindPath, {
        version: 1,
        assetId: asset.assetId,
        sha256: asset.sha256,
        listener: "gemini-3.1-pro",
        heardText,
        heardIpa: String(heard.bestEffortIpa ?? "").trim() || null,
        detectedLanguage: heard.detectedLanguage ?? asset.languageId,
        confidence: heard.confidence ?? null,
        modelRevision: model,
        promptPolicyVersion: "reference-free-audio-v1",
        targetTextSent: false,
        originalFilenameSent: false,
        createdAt: new Date().toISOString(),
        outcome: classifyBlindTranscript({
          expected: asset.text,
          actual: heardText,
          languageId: asset.languageId,
          homophoneGroups,
          cmuReference: cmu,
        }),
      });
      console.log(
        `Gemini blind ${mode} ${index + 1}/${items.length}: ${asset.assetId}`,
      );
    } catch (error) {
      failures.push({
        assetId: asset.assetId,
        error: String(error?.message ?? error),
      });
    }
  }
  const observations = readJsonl(geminiBlindPath);
  const smokeObservations = selected
    .map((asset) => observations.find((row) => row.sha256 === asset.sha256))
    .filter(Boolean);
  const stableCount = smokeObservations.filter((row) =>
    ["exact", "accepted-homophone", "orthographic-variant"].includes(
      row.outcome,
    ),
  ).length;
  const passed =
    failures.length === 0 &&
    smokeObservations.length === selected.length &&
    (mode !== "smoke" || stableCount >= Math.ceil(selected.length * 0.75));
  const summary = {
    mode,
    generatedAt: new Date().toISOString(),
    requested: selected.length,
    attempted: items.length,
    stableCount,
    failed: failures.length,
    failures,
    passed,
    loopbackOnly: baseUrl.hostname === "127.0.0.1",
  };
  writeJson(path.join(blindRoot, `gemini-${mode}-summary.json`), summary);
  if (!passed) process.exitCode = 1;
}

