function referenceCommand() {
  const inventory = requireInventory();
  const cmu = loadCmuDictReference();
  const baseEntries = buildGoldPronunciations(inventory, cmu);
  const decisionLedger = JSON.parse(
    readFileSync(referenceDecisionPath, "utf8"),
  );
  const entries = applyGoldPronunciationDecisions(baseEntries, decisionLedger);
  const document = {
    version: 1,
    generatedAt: new Date().toISOString(),
    warning:
      "No entry is two-source-confirmed until the Wiktionary/native review decision is imported. CMUdict and project metadata remain separate evidence.",
    sourcePolicy: {
      "en-US": [
        "CMUdict",
        "structured Wiktionary en-US",
        "MW/Cambridge on conflict",
      ],
      "es-ES": [
        "structured Wiktionary es-ES",
        "Peninsular Spanish rules",
        "native review on conflict",
      ],
      "fr-FR": [
        "structured Wiktionary fr-FR",
        "native review for schwa/final-consonant variants",
      ],
      "ru-RU": [
        "structured Wiktionary ru-RU stress/IPA",
        "native review for reduction/assimilation",
      ],
    },
    entryCount: entries.length,
    statusCounts: countBy(entries, (entry) => entry.referenceStatus),
    entries,
  };
  writeJson(referencePath, document);
  const conflicts = entries.filter((entry) => entry.status === "conflict");
  writeJson(path.join(outputRoot, "reference-conflicts.json"), {
    version: 1,
    generatedAt: document.generatedAt,
    conflictCount: conflicts.length,
    entries: conflicts,
  });
  const relationshipRiskKeys = new Set(
    inventory.assets
      .filter((asset) => asset.relationshipIssues.length > 0 && asset.text)
      .map(
        (asset) =>
          `${asset.languageId}\u0000${asset.text.toLocaleLowerCase(asset.languageId)}`,
      ),
  );
  const languageAnchor = {
    "en-US": "English",
    "es-ES": "Spanish",
    "fr-FR": "French",
    "ru-RU": "Russian",
  };
  const reviewItems = entries
    .map((entry) => {
      const relationshipRisk = relationshipRiskKeys.has(
        `${entry.languageId}\u0000${entry.text.toLocaleLowerCase(entry.languageId)}`,
      );
      const priority =
        relationshipRisk || entry.status === "conflict"
          ? "P0"
          : entry.languageId === "en-US"
            ? "P1"
            : "P2-native";
      return {
        languageId: entry.languageId,
        text: entry.text,
        priority,
        relationshipRisk,
        referenceStatus: entry.referenceStatus,
        projectIpas: entry.projectIpas,
        candidateCanonicalIpa: entry.canonicalIpa,
        sourceLinks: {
          wiktionary: `https://en.wiktionary.org/wiki/${encodeURIComponent(
            entry.text,
          )}#${languageAnchor[entry.languageId]}`,
          ...(entry.languageId === "en-US" && entry.status === "conflict"
            ? {
                merriamWebster: `https://www.merriam-webster.com/dictionary/${encodeURIComponent(entry.text)}`,
                cambridge: `https://dictionary.cambridge.org/us/dictionary/english/${encodeURIComponent(
                  entry.text.toLocaleLowerCase("en-US").replaceAll(" ", "-"),
                )}`,
              }
            : {}),
        },
      };
    })
    .sort((left, right) =>
      `${left.priority}:${left.languageId}:${left.text}`.localeCompare(
        `${right.priority}:${right.languageId}:${right.text}`,
      ),
    );
  writeJson(path.join(outputRoot, "reference-review-queue.json"), {
    version: 1,
    generatedAt: document.generatedAt,
    warning:
      "Links support human reference review; their audio must not be copied into the product.",
    statusCounts: countBy(reviewItems, (item) => item.priority),
    items: reviewItems,
  });
  console.log(
    `Reference queue: ${entries.length} words; ${conflicts.length} conflict/missing-CMU entries; all still require an independent second source.`,
  );
}

