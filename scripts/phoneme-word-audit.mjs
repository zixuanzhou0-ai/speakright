async function main() {
  const parsed = parseArgs(process.argv.slice(2));
  switch (parsed.command) {
    case "inventory":
      inventoryCommand();
      break;
    case "reference":
      referenceCommand();
      break;
    case "blind-plan":
      blindPlanCommand();
      break;
    case "whisper":
      whisperCommand();
      break;
    case "azure-stt-run":
      await azureSttRunCommand(parsed);
      break;
    case "gemini-smoke":
      await geminiRunCommand(parsed, "smoke");
      break;
    case "gemini-run":
      await geminiRunCommand(parsed, parsed.valueFor("--mode", "full"));
      break;
    case "align-english":
      alignmentCommand();
      break;
    case "consensus":
      consensusCommand();
      break;
    case "review":
      reviewCommand();
      break;
    case "regenerate-plan":
      regeneratePlanCommand(parsed);
      break;
    case "regenerate":
      throw new Error(
        "Paid regeneration remains locked until an exact reviewed plan receives a separate confirmation.",
      );
    case "gate":
      gateCommand(parsed);
      break;
    case "report":
      reportCommand();
      break;
    default:
      throw new Error(`Unknown command: ${parsed.command ?? "(missing)"}`);
  }
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
});
