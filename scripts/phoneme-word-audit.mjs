function gateCommand(parsed) {
  const stage = parsed.valueFor("--stage", "final");
  if (!["baseline", "machine", "final"].includes(stage)) {
    throw new Error(`Unsupported gate stage: ${stage}`);
  }
  const inventory = requireInventory();
  const failures = [];
  if (inventory.assetCount !== EXPECTED_PHONEME_PAGE_ASSET_COUNT)
    failures.push("asset-count");
  if (inventory.wordBearingCount !== EXPECTED_WORD_BEARING_ASSET_COUNT)
    failures.push("word-count");
  if (inventory.anchorCount !== EXPECTED_ANCHOR_ASSET_COUNT)
    failures.push("anchor-count");
  if (inventory.hardIssues.length)
    failures.push(`${inventory.hardIssues.length}-hard-inventory-issues`);
  const whispers = readJsonl(whisperBlindPath);
  if (whispers.length !== EXPECTED_WORD_BEARING_ASSET_COUNT) {
    failures.push(
      `whisper-${whispers.length}/${EXPECTED_WORD_BEARING_ASSET_COUNT}`,
    );
  }
  if (["machine", "final"].includes(stage)) {
    const azures = readJsonl(azureBlindPath);
    const geminis = readJsonl(geminiBlindPath);
    if (azures.length !== EXPECTED_WORD_BEARING_ASSET_COUNT) {
      failures.push(
        `azure-stt-${azures.length}/${EXPECTED_WORD_BEARING_ASSET_COUNT}`,
      );
    }
    if (geminis.length !== EXPECTED_WORD_BEARING_ASSET_COUNT) {
      failures.push(
        `gemini-${geminis.length}/${EXPECTED_WORD_BEARING_ASSET_COUNT}`,
      );
    }
  }
  if (stage === "final") {
    const reference = existsSync(referencePath)
      ? readJson(referencePath)
      : null;
    const unresolvedReferences = (reference?.entries ?? []).filter(
      (entry) =>
        !["two-source-confirmed", "variant-confirmed"].includes(entry.status),
    );
    if (unresolvedReferences.length) {
      failures.push(`${unresolvedReferences.length}-unresolved-references`);
    }
    const decisionsPath = path.join(
      outputRoot,
      "human-auditory-decisions.json",
    );
    if (!existsSync(decisionsPath)) failures.push("human-decisions-missing");
    else {
      const reviewDocument = readJson(decisionsPath);
      const decisions = reviewDocument.assets ?? {};
      const blindReviewCount = Object.keys(
        reviewDocument.blindReviews ?? {},
      ).length;
      if (blindReviewCount !== 4770) {
        failures.push(`${blindReviewCount}/4770-blind-review-items`);
      }
      const unresolved = inventory.assets.filter((asset) => {
        const status = decisions[asset.assetId]?.status;
        return ![
          "verified-auditory",
          "verified-variant",
          "replaced-and-verified",
        ].includes(status);
      });
      if (unresolved.length)
        failures.push(`${unresolved.length}-unresolved-human-decisions`);
      const invalid = Object.values(decisions).filter(
        (decision) => !WORD_AUDIT_FINAL_STATUSES.includes(decision.status),
      );
      if (invalid.length) failures.push(`${invalid.length}-invalid-statuses`);
    }
  }
  if (failures.length) {
    console.error(`Phoneme-word ${stage} gate failed:`);
    for (const failure of failures) console.error(`- ${failure}`);
    process.exitCode = 1;
  } else {
    console.log(
      `Phoneme-word ${stage} gate passed (${inventory.assetCount} assets).`,
    );
  }
}

